export function translateDemoText(text: string, locale: string): string {
  if (locale !== 'en') return text;
  if (text.endsWith(' empfangen')) return `${english[text.slice(0, -10)] ?? text.slice(0, -10)} received`;
  return english[text] ?? text;
}
export function useDemoText(): (text: string) => string {
  const locale = useLocale();
  return text => translateDemoText(text, locale);
}
